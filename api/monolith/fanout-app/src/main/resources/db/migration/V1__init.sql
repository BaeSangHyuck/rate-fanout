-- H2(로컬·테스트)와 Postgres(배포) 둘 다에서 도는 문법만 쓴다
create table product (
  id varchar(36) primary key,
  stock int not null
);

create table outbox (
  event_id varchar(36) primary key,
  run_id varchar(36) not null,
  type varchar(32) not null,
  order_no int not null,
  published boolean default false not null
);
create index idx_outbox_pending on outbox (run_id, published);

create table processed_event (
  event_id varchar(36) primary key,
  run_id varchar(36) not null
);
create index idx_processed_event_run on processed_event (run_id);

create table coupon (
  id varchar(36) primary key,
  remaining int not null
);

create table coupon_issue (
  id bigint generated by default as identity primary key,
  coupon_id varchar(36) not null,
  user_id int not null,
  constraint uk_coupon_issue_user unique (coupon_id, user_id)
);
